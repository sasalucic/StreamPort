const {chromium}=require('playwright');const fs=require('fs'),path=require('path'),assert=require('assert');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:393,height:852},deviceScaleFactor:1});
 const base=path.resolve(__dirname,'../../StreamPort/static'),assets=path.resolve(__dirname,'../app/src/main/assets');
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setContent(fs.readFileSync(path.join(base,'index.html'),'utf8').replace(/<script[\s\S]*?<\/script>/g,'').replace(/<link[^>]+>/g,''));
 await page.addStyleTag({path:path.join(base,'style.css')});
 await page.addScriptTag({path:path.join(base,'app.js')});
 await page.addScriptTag({content:fs.readFileSync(path.join(base,'enhancements.js'),'utf8').replace(/boot\(\);\s*$/,'')});
 await page.evaluate(async()=>{me={admin:false,name:'Viewer'};library=[];shell();await render();});
 await page.addStyleTag({path:path.join(assets,'mobile.css')});
 await page.addScriptTag({path:path.join(assets,'mobile.js')});
 await page.evaluate(()=>{document.querySelector('#playing-title').textContent='Avatar: Fire and Ash';document.querySelector('#audio-track').innerHTML='<option>English · AAC</option>';document.querySelector('#duration-label').textContent='3:17:08';document.querySelector('#seek').max=11828;document.querySelector('#seek').value=6;document.querySelector('#player').showModal();});
 await page.waitForTimeout(100);
 assert(await page.locator('#player').evaluate(e=>e.clientWidth===innerWidth));
 assert(!(await page.locator('.sp-sheet-mask').evaluate(e=>e.classList.contains('open'))));
 assert(!(await page.locator('#video').evaluate(e=>e.controls)));
 assert.equal(await page.locator('#android-app-options').count(),1);
 await page.screenshot({path:path.resolve(__dirname,'../../android-tools/mobile-player-preview.png')});
 await page.getByRole('button',{name:'Subtitles',exact:true}).click();
 assert(await page.locator('.sp-sheet-mask').evaluate(e=>e.classList.contains('open')));await page.getByRole('button',{name:'Close settings'}).click();
 await page.evaluate(()=>{window.seekSeen=null;document.querySelector('#seek').onchange=e=>window.seekSeen=Number(e.target.value);});
 await page.getByRole('button',{name:'Forward 10 seconds'}).click();assert.equal(await page.evaluate(()=>window.seekSeen),16);
 await page.getByRole('button',{name:'Back 10 seconds'}).click();assert.equal(await page.evaluate(()=>window.seekSeen),6);
 await page.evaluate(()=>{document.querySelector('#player').close();shell();});await page.waitForTimeout(100);
 assert.equal(await page.locator('.app-header #android-app-options').count(),1);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 await browser.close();console.log('Immersive mobile layout, settings sheets, seeking and menu regeneration passed at 393 × 852.');
})().catch(e=>{console.error(e);process.exit(1)});
